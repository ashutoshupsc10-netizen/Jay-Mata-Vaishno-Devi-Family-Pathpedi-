        private fun decodeJsString(value: String): String {
            if (
                value.length >= 2 &&
                value.first() == '"' &&
                value.last() == '"'
            ) {
                return try {
                    org.json.JSONTokener(value)
                        .nextValue()
                        .toString()
                } catch (e: Exception) {
                    value.substring(1, value.length - 1)
                }
            }
            return value
        }
    }
